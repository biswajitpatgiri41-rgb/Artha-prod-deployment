@router.post("/{update_id}/validate", response_model=UploadMetadata, dependencies=[Depends(require_permission(Permission.DATASET_WRITE.value))])
async def validate_data_update(
    update_id: str,
    request: ValidationRequest,
) -> UploadMetadata:
    """
    Validate an uploaded data file.
    Performs parsing, schema validation, and comparison with existing data.
    """
    metadata = _load_metadata(update_id)
    
    if metadata["status"] in (UploadStatus.APPLIED, UploadStatus.REJECTED):
        raise HTTPException(status_code=400, detail=f"Update already {metadata['status'].lower()}")
    
    # Update status
    metadata["status"] = UploadStatus.PARSING
    _save_metadata(update_id, metadata)
    
    # Parse file
    original_path = ROOT / metadata["original_file"]
    content = original_path.read_bytes()
    df = _parse_file(content, metadata["original_filename"])
    
    if len(df) > MAX_UPLOAD_ROWS:
        raise HTTPException(status_code=422, detail=f"Too many rows: {len(df)} (max {MAX_UPLOAD_ROWS})")
    
    metadata["status"] = UploadStatus.VALIDATING
    _save_metadata(update_id, metadata)
    
    # Detect provider and series
    provider, detected_series = _detect_provider_and_series(df)
    
    # If manual mapping provided, use it
    series_id = request.series_id or detected_series
    source = request.source
    unit = request.unit
    frequency = request.frequency
    
    # If still no series_id, return NEEDS_MAPPING
    if not series_id:
        metadata["status"] = UploadStatus.NEEDS_MAPPING
        metadata["needs_mapping"] = True
        metadata["mapping_options"] = {
            "available_series": list(SERIES_REGISTRY.keys()),
            "detected_provider": provider,
            "columns": list(df.columns),
            "row_count": len(df),
        }
        _save_metadata(update_id, metadata)
        return UploadMetadata(**metadata)
    
    # Validate series exists in registry
    if series_id not in SERIES_REGISTRY:
        raise HTTPException(status_code=422, detail=f"Unknown series_id: {series_id}")
    
    registry_entry = SERIES_REGISTRY[series_id]
    
    # Use registry defaults if not provided
    if not source:
        source = registry_entry.preferred_source.value
    if not unit:
        unit = registry_entry.unit
    if not frequency:
        frequency = registry_entry.frequency.value
    
    # Validate frequency
    try:
        freq_enum = Frequency(frequency)
    except ValueError:
        raise HTTPException(status_code=422, detail=f"Invalid frequency: {frequency}")
    
    # Validate source
    try:
        source_enum = Source(source)
    except ValueError:
        raise HTTPException(status_code=422, detail=f"Unknown source: {source}")
    
    # Find columns
    date_col = _find_column(df, {"obs_date", "date", "observation_date", "period", "time"})
    series_col = _find_column(df, {"series_id", "series", "id"})
    value_col = _find_column(df, {"value", "val", "observation", "data_value"})
    unit_col = _find_column(df, {"unit", "units", "uom"})
    freq_col = _find_column(df, {"frequency", "freq", "periodicity"})
    source_col = _find_column(df, {"source", "src", "provider"})
    source_url_col = _find_column(df, {"source_url", "url", "sourceurl"})
    release_col = _find_column(df, {"release_date", "releasedate", "publication_date", "pub_date"})
    base_col = _find_column(df, {"base_year", "baseyear", "base"})
    revision_col = _find_column(df, {"revision_tag", "revision", "tag", "vintage"})
    seasonal_col = _find_column(df, {"seasonal_adjustment", "seasonal", "sa", "adjustment"})
    
    # Required columns check
    missing = []
    if not date_col:
        missing.append("obs_date/date")
    if not value_col:
        missing.append("value")
    if missing:
        raise HTTPException(status_code=422, detail=f"Missing required columns: {', '.join(missing)}")
    
    # Load existing observations for comparison
    existing_obs = _load_existing_observations(series_id)
    
    # Parse and validate each row
    parsed_observations = []
    validation_errors = []
    
    for idx, row in df.iterrows():
        try:
            # Parse date
            raw_date = row[date_col]
            if pd.isna(raw_date):
                validation_errors.append(f"Row {idx}: Missing date")
                continue
            obs_date = pd.to_datetime(raw_date).date()
            
            # Parse value
            raw_value = row[value_col]
            if pd.isna(raw_value):
                validation_errors.append(f"Row {idx}: Missing value")
                continue
            value = float(raw_value)
            if not (value == value and value != float('inf') and value != float('-inf')):
                validation_errors.append(f"Row {idx}: Value must be finite")
                continue
            
            # Get unit
            row_unit = str(row[unit_col]).strip() if unit_col and pd.notna(row[unit_col]) else unit
            
            # Get frequency
            row_freq = str(row[freq_col]).strip().upper() if freq_col and pd.notna(row[freq_col]) else frequency
            try:
                row_freq_enum = Frequency(row_freq)
            except ValueError:
                validation_errors.append(f"Row {idx}: Invalid frequency '{row_freq}'")
                continue
            
            # Get source
            row_source = str(row[source_col]).strip() if source_col and pd.notna(row[source_col]) else source
            try:
                Source(row_source)
            except ValueError:
                validation_errors.append(f"Row {idx}: Unknown source '{row_source}'")
                continue
            
            # Optional fields
            row_source_url = str(row[source_url_col]).strip() if source_url_col and pd.notna(row[source_url_col]) else None
            row_release = None
            if release_col and pd.notna(row[release_col]):
                try:
                    row_release = pd.to_datetime(row[release_col]).date()
                except Exception:
                    pass
            row_base = str(row[base_col]).strip() if base_col and pd.notna(row[base_col]) else registry_entry.base_year
            row_revision = str(row[revision_col]).strip() if revision_col and pd.notna(row[revision_col]) else "uploaded"
            row_seasonal = str(row[seasonal_col]).strip().upper() if seasonal_col and pd.notna(row[seasonal_col]) else "UNKNOWN"
            try:
                row_seasonal_enum = SeasonalAdjustment(row_seasonal)
            except ValueError:
                row_seasonal_enum = SeasonalAdjustment.UNKNOWN
            
            # Create observation
            obs = MacroObservation(
                obs_date=obs_date,
                series_id=series_id,
                value=value,
                unit=row_unit,
                frequency=row_freq_enum,
                source=row_source,
                source_url=row_source_url,
                release_date=row_release,
                base_year=row_base,
                seasonal_adjustment=row_seasonal_enum,
                revision_tag=row_revision,
                retrieved_at=datetime.now(timezone.utc),
            )
            
            # Validate against schema
            errors = validate_observation(obs, SERIES_REGISTRY)
            if errors:
                validation_errors.append(f"Row {idx}: {'; '.join(errors)}")
                continue
            
            parsed_observations.append(obs)
            
        except Exception as e:
            validation_errors.append(f"Row {idx}: {e}")
    
    # Check for duplicates in upload
    duplicates = detect_duplicates(parsed_observations)
    if duplicates:
        for i, j in duplicates:
            validation_errors.append(f"Duplicate observations at indices {i} and {j}: same series/date")
# Classify each observation
    preview_rows = []
    new_count = 0
    revision_count = 0
    conflict_count = 0
    same_count = 0
    
    for obs in parsed_observations:
        existing = existing_obs.get(obs.obs_date.isoformat())
        status, reason = _classify_observation(obs, existing, registry_entry)
        
        if status == ObservationStatus.NEW:
            new_count += 1
        elif status == ObservationStatus.REVISION:
            revision_count += 1
        elif status == ObservationStatus.CONFLICT:
            conflict_count += 1
        elif status == ObservationStatus.SAME:
            same_count += 1
        
        preview_rows.append(PreviewRow(
            date=obs.obs_date.isoformat(),
            existing_value=existing.value if existing else None,
            uploaded_value=obs.value,
            status=status,
        ))
    
    # Build validation results
    validation_checks = [
        ValidationCheck(check="Schema", status="PASS" if not validation_errors else "FAIL", 
                       details=f"{len(validation_errors)} errors" if validation_errors else None),
        ValidationCheck(check="Dates", status="PASS" if all(o.obs_date for o in parsed_observations) else "FAIL"),
        ValidationCheck(check="Values", status="PASS" if all(o.value is not None and o.value == o.value for o in parsed_observations) else "FAIL"),
        ValidationCheck(check="Units", status="PASS" if all(o.unit for o in parsed_observations) else "FAIL"),
        ValidationCheck(check="Duplicates", status="PASS" if not duplicates else "FAIL",
                       details=f"{len(duplicates)} duplicates found" if duplicates else None),
        ValidationCheck(check="Base Year", status="PASS" if not registry_entry.base_year or all(
            o.base_year == registry_entry.base_year for o in parsed_observations if o.base_year
        ) else "WARNING",
                       details="Base year mismatch with registry" if registry_entry.base_year and any(
                           o.base_year and o.base_year != registry_entry.base_year for o in parsed_observations
                       ) else None),
        ValidationCheck(check="Provenance", status="PASS" if all(o.source for o in parsed_observations) else "FAIL"),
    ]
    
    # Detected data
    dates = [o.obs_date for o in parsed_observations]
    detected = DetectedData(
        source=source,
        series=series_id,
        frequency=frequency,
        unit=unit,
        base_year=registry_entry.base_year,
        date_range=f"{min(dates).isoformat()} to {max(dates).isoformat()}" if dates else None,
        observation_count=len(parsed_observations),
    )
    
    # Update metadata
    metadata["status"] = UploadStatus.READY_FOR_REVIEW if not validation_errors else UploadStatus.REJECTED
    metadata["detected_data"] = detected.model_dump()
    metadata["validation_results"] = [v.model_dump() for v in validation_checks]
    metadata["preview_data"] = {
        "rows": [r.model_dump() for r in preview_rows],
        "summary": {
            "new": new_count,
            "revisions": revision_count,
            "conflicts": conflict_count,
            "same": same_count,
        },
    }
    metadata["series_id"] = series_id
    metadata["provider"] = provider
    _save_metadata(update_id, metadata)
    
    return UploadMetadata(**metadata)
@router.get("/{update_id}/preview", response_model=PreviewResponse)
async def get_preview(update_id: str) -> PreviewResponse:
    """Get the preview of changes for a validated update."""
    metadata = _load_metadata(update_id)
    
    if metadata["status"] not in (UploadStatus.READY_FOR_REVIEW, UploadStatus.APPLIED):
        raise HTTPException(status_code=400, detail="Update not ready for preview")
    
    preview = metadata.get("preview_data")
    if not preview:
        raise HTTPException(status_code=404, detail="No preview data available")
    
    return PreviewResponse(
        update_id=update_id,
        rows=[PreviewRow(**r) for r in preview["rows"]],
        summary=preview["summary"],
    )
@router.post("/{update_id}/apply", response_model=ApplyResponse, dependencies=[Depends(require_permission(Permission.DATASET_WRITE.value))])
async def apply_data_update(update_id: str, request: ApplyRequest) -> ApplyResponse:
    """
    Apply a validated data update.
    Promotes observations from staging to canonical store.
    Preserves vintages for revisions.
    """
    metadata = _load_metadata(update_id)
    
    if metadata["status"] != UploadStatus.READY_FOR_REVIEW:
        raise HTTPException(status_code=400, detail=f"Update not ready for application (status: {metadata['status']})")
    
    if metadata.get("preview_data", {}).get("summary", {}).get("conflicts", 0) > 0:
        raise HTTPException(status_code=400, detail="Cannot apply update with conflicts. Resolve conflicts first.")
    
    series_id = metadata.get("series_id")
    if not series_id:
        raise HTTPException(status_code=400, detail="No series_id in metadata")
    
    preview = metadata["preview_data"]
    rows = preview["rows"]
    summary = preview["summary"]
    
    # Load existing observations
    existing_obs = _load_existing_observations(series_id)
    
    # Build new observation set (preserving vintages)
    updated_observations = {}
    
    # Start with existing
    for date, obs in existing_obs.items():
        updated_observations[date] = obs
    
    # Apply new/revised observations
    for row in rows:
        if row["status"] in (ObservationStatus.NEW, ObservationStatus.REVISION):
            date = row["date"]
            if row["status"] == ObservationStatus.REVISION:
                existing = existing_obs.get(date)
                if existing:
                    existing.revision_tag = f"superseded_by_{update_id}"
            new_obs = MacroObservation(
                obs_date=datetime.fromisoformat(date).date(),
                series_id=series_id,
                value=row["uploaded_value"],
                unit=metadata.get("detected_data", {}).get("unit", ""),
                frequency=Frequency(metadata.get("detected_data", {}).get("frequency", "M")),
                source=metadata.get("detected_data", {}).get("source", ""),
                revision_tag=metadata.get("original_filename", "uploaded"),
                retrieved_at=datetime.now(timezone.utc),
            )
            updated_observations[date] = new_obs
    
    # Sort and save
    sorted_obs = [updated_observations[key] for key in sorted(updated_observations)]
    
    # Save to interim (canonical store)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S_%f")
    interim_path = INTERIM_DIR / f"{series_id}_normalized_upload_{stamp}.json"
    INTERIM_DIR.mkdir(parents=True, exist_ok=True)
    
    interim_path.write_text(
        json.dumps({
            "mode": "upsert",
            "observations": [o.to_dict() for o in sorted_obs],
            "applied_from_update": update_id,
            "applied_at": datetime.now(timezone.utc).isoformat(),
        }, ensure_ascii=False, indent=2),
        encoding="utf-8"
    )
    
    # Update manifest
    manifest = {
        "series_id": series_id,
        "original_filename": metadata["original_filename"],
        "sha256": metadata["sha256"],
        "uploaded_at_utc": metadata["uploaded_at"],
        "applied_at_utc": datetime.now(timezone.utc).isoformat(),
        "update_id": update_id,
        "new_observations": summary["new"],
        "revisions": summary["revisions"],
        "conflicts": summary["conflicts"],
        "same": summary["same"],
        "start_date": min(updated_observations) if updated_observations else None,
        "end_date": max(updated_observations) if updated_observations else None,
    }
    MANIFESTS_DIR.mkdir(parents=True, exist_ok=True)
    manifest_path = MANIFESTS_DIR / f"data_update_{series_id}_{stamp}.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    
    # Update metadata
    metadata["status"] = UploadStatus.APPLIED
    metadata["applied_at"] = datetime.now(timezone.utc).isoformat()
    _save_metadata(update_id, metadata)
    
    # Check if model refresh needed
    model_refresh = series_id in {"cpi_headline", "food_inflation", "cpi_yoy", "repo_rate", "brent_crude", "inr_usd"}
    
    return ApplyResponse(
        update_id=update_id,
        series_updated=[series_id],
        new_observations=summary["new"],
        revisions=summary["revisions"],
        affected_date_range=f"{manifest['start_date']} to {manifest['end_date']}" if manifest["start_date"] else None,
        feature_rebuild_status="pending" if model_refresh else "not_required",
        dashboard_data_version=stamp,
        model_refresh_required=model_refresh,
    )


@router.delete("/{update_id}", dependencies=[Depends(require_permission(Permission.DATASET_DELETE.value))])
async def delete_data_update(update_id: str) -> dict:
    """Delete a data update (only if not applied)."""
    metadata = _load_metadata(update_id)
    
    if metadata["status"] == UploadStatus.APPLIED:
        raise HTTPException(status_code=400, detail="Cannot delete applied update")
    
    # Delete staging directory
    staging_path = _get_staging_path(update_id)
    import shutil
    shutil.rmtree(staging_path, ignore_errors=True)
    
    return {"status": "deleted", "update_id": update_id}
