@router.post("/upload", response_model=UploadResponse, status_code=status.HTTP_201_CREATED, dependencies=[Depends(require_permission(Permission.DATASET_UPLOAD.value))])
async def upload_data_update(
    file: UploadFile = File(...),
) -> UploadResponse:
    """
    Upload an economic data file for processing.
    Files go to staging, NOT to processed/canonical data.
    """
    content = await file.read()
    if not content:
        raise HTTPException(status_code=422, detail="Empty file")
    
    filename = file.filename or "unknown"
    _validate_file_security(filename, content)
    
    # Generate update ID
    update_id = _generate_update_id()
    staging_path = _get_staging_path(update_id)
    
    # Save original file
    original_path = staging_path / filename
    original_path.write_bytes(content)
    
    # Compute SHA256
    sha256 = hashlib.sha256(content).hexdigest()
    
    # Create initial metadata
    metadata = {
        "update_id": update_id,
        "original_filename": filename,
        "sha256": sha256,
        "uploaded_at": datetime.now(timezone.utc).isoformat(),
        "size": len(content),
        "format": Path(filename).suffix.lower(),
        "status": UploadStatus.UPLOADING,
        "original_file": str(original_path.relative_to(ROOT)),
    }
    _save_metadata(update_id, metadata)
    
    return UploadResponse(
        update_id=update_id,
        status=UploadStatus.UPLOADING,
        message="File uploaded successfully. Processing will begin."
    )


