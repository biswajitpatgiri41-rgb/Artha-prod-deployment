def _generate_update_id() -> str:
    """Generate a unique update ID."""
    return f"upd_{datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')}_{uuid.uuid4().hex[:8]}"


def _get_staging_path(update_id: str) -> Path:
    """Get the staging directory for an update."""
    # Update IDs are generated by this module and have a fixed shape. Treat
    # IDs from route parameters as untrusted before using them in a path.
    if not re.fullmatch(r"upd_\d{8}_\d{6}_[0-9a-f]{8}", update_id):
        raise HTTPException(status_code=404, detail="Update not found")
    path = STAGING_DIR / update_id
    path.mkdir(parents=True, exist_ok=True)
    return path


def _get_metadata_path(update_id: str) -> Path:
    """Get the metadata file path for an update."""
    return _get_staging_path(update_id) / "metadata.json"


def _save_metadata(update_id: str, metadata: dict) -> None:
    """Save metadata to staging directory."""
    path = _get_metadata_path(update_id)
    path.write_text(json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8")


def _load_metadata(update_id: str) -> dict:
    """Load metadata from staging directory."""
    path = _get_metadata_path(update_id)
    if not path.exists():
        raise HTTPException(status_code=404, detail="Update not found")
    return json.loads(path.read_text(encoding="utf-8"))


def _validate_file_security(filename: str, content: bytes) -> None:
    """Validate file for security issues."""
    # Path traversal
    if check_path_traversal(filename):
        raise HTTPException(status_code=422, detail="Invalid filename: path traversal detected")
    
    # Extension check
    ext = Path(filename).suffix.lower()
    if ext not in SUPPORTED_EXTENSIONS:
        raise HTTPException(
            status_code=422,
            detail=f"Unsupported file format: {ext}. Supported: {', '.join(SUPPORTED_EXTENSIONS)}"
        )
    
    # Size check
    if len(content) > MAX_UPLOAD_BYTES:
        raise HTTPException(
            status_code=422,
            detail=f"File too large: {len(content)} bytes (max {MAX_UPLOAD_BYTES})"
        )
    
    # Empty file check
    if len(content) == 0:
        raise HTTPException(status_code=422, detail="Empty file")
def _parse_csv(content: bytes) -> pd.DataFrame:
    """Parse CSV content."""
    try:
        return pd.read_csv(pd.io.common.BytesIO(content))
    except Exception as e:
        raise HTTPException(status_code=422, detail=f"Failed to parse CSV: {e}")


def _parse_xlsx(content: bytes) -> pd.DataFrame:
    """Parse XLSX content."""
    try:
        return pd.read_excel(pd.io.common.BytesIO(content), engine="openpyxl")
    except Exception as e:
        raise HTTPException(status_code=422, detail=f"Failed to parse XLSX: {e}")


def _parse_json(content: bytes) -> pd.DataFrame:
    """Parse JSON content."""
    try:
        data = json.loads(content.decode("utf-8"))
        if isinstance(data, list):
            return pd.DataFrame(data)
        elif isinstance(data, dict):
            for key in ["observations", "data", "records", "values"]:
                if key in data and isinstance(data[key], list):
                    return pd.DataFrame(data[key])
            return pd.DataFrame([data])
        else:
            raise ValueError("JSON must be an array or object with observations array")
    except Exception as e:
        raise HTTPException(status_code=422, detail=f"Failed to parse JSON: {e}")


def _parse_file(content: bytes, filename: str) -> pd.DataFrame:
    """Parse file based on extension."""
    ext = Path(filename).suffix.lower()
    if ext == ".csv":
        return _parse_csv(content)
    elif ext == ".xlsx":
        return _parse_xlsx(content)
    elif ext == ".json":
        return _parse_json(content)
    else:
        raise HTTPException(status_code=422, detail=f"Unsupported format: {ext}")
def _normalize_column_name(col: str) -> str:
    """Normalize column name for matching."""
    return re.sub(r"[^a-z0-9]+", "_", col.strip().lower()).strip("_")


def _find_column(df: pd.DataFrame, candidates: set[str]) -> Optional[str]:
    """Find a column by normalized name."""
    normalized = {_normalize_column_name(c): c for c in df.columns}
    for candidate in candidates:
        if candidate in normalized:
            return normalized[candidate]
    return None


def _detect_provider_and_series(df: pd.DataFrame) -> tuple[Optional[str], Optional[str]]:
    """
    Attempt to detect provider and series from the data.
    Returns (provider, series_id) or (None, None) if uncertain.
    """
    # Check for provider-specific patterns
    cols = {_normalize_column_name(c): c for c in df.columns}
    
    # MoSPI native CPI XLSX often has specific column patterns
    if "cpi" in cols and "index" in cols and "rural" in cols and "urban" in cols:
        return "MOSPI", "cpi_headline"
    
    # RBI native workbook patterns
    if "repo" in cols or "policy_rate" in cols:
        return "RBI", "repo_rate"
    
    # Generic canonical schema columns
    required = {"obs_date", "series_id", "value", "unit", "frequency", "source"}
    if required.issubset(cols):
        # Try to get series_id from first row
        series_col = _find_column(df, {"series_id"})
        if series_col:
            values = df[series_col].dropna()
            first_series = str(values.iloc[0]).strip() if not values.empty else None
            if first_series and first_series in SERIES_REGISTRY:
                return "CANONICAL", first_series
        return "CANONICAL", None
    
    return None, None


def _load_existing_observations(series_id: str) -> dict[str, MacroObservation]:
    """Load existing observations for a series from interim storage."""
    existing = {}
    for path in sorted(INTERIM_DIR.glob(f"{series_id}_normalized_*.json"), key=lambda p: p.stat().st_mtime):
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
            observations = payload.get("observations", []) if isinstance(payload, dict) else payload
            for item in observations:
                obs_date = str(item.get("obs_date", ""))[:10]
                if obs_date:
                    existing[obs_date] = MacroObservation.from_dict(item)
        except Exception:
            continue
    return existing


def _classify_observation(
    uploaded: MacroObservation,
    existing: Optional[MacroObservation],
    registry_entry: Optional[SeriesRegistryEntry]
) -> tuple[str, Optional[str]]:
    """
    Classify an observation as NEW, SAME, REVISION, or CONFLICT.
    Returns (status, reason).
    """
    if existing is None:
        return ObservationStatus.NEW, "No existing observation for this date"
    
    # Check if values are the same (within small tolerance)
    if existing.value is not None and uploaded.value is not None:
        if abs(existing.value - uploaded.value) < 1e-10:
            return ObservationStatus.SAME, "Value matches existing observation"
    
    # Check for conflicts
    conflict_reasons = []
    
    # Unit mismatch
    if registry_entry and existing.unit != uploaded.unit:
        if registry_entry.unit != uploaded.unit:
            conflict_reasons.append(f"Unit mismatch: existing={existing.unit}, uploaded={uploaded.unit}, registry={registry_entry.unit}")
    
    # Frequency mismatch
    if registry_entry and existing.frequency != uploaded.frequency:
        if registry_entry.frequency != uploaded.frequency:
            conflict_reasons.append(f"Frequency mismatch: existing={existing.frequency}, uploaded={uploaded.frequency}, registry={registry_entry.frequency}")
    
    # Base year mismatch
    if existing.base_year and uploaded.base_year and existing.base_year != uploaded.base_year:
        conflict_reasons.append(f"Base year mismatch: existing={existing.base_year}, uploaded={uploaded.base_year}")
    
    # Source mismatch (different methodology)
    if existing.source != uploaded.source:
        conflict_reasons.append(f"Source mismatch: existing={existing.source}, uploaded={uploaded.source}")
    
    if conflict_reasons:
        return ObservationStatus.CONFLICT, "; ".join(conflict_reasons)
    
    # If value differs but no conflicts, it's a revision
    return ObservationStatus.REVISION, "Value revised by official source"
