content += (
    "\n"
    "export function AdminAuthProvider({ children }: { children: ReactNode }) {\n"
    "  const [state, setState] = useState<AuthState>({\n"
    "    user: null,\n"
    "    isLoading: true,\n"
    "    isAuthenticated: false,\n"
    "    error: null,\n"
    "  });\n"
    "  const router = useRouter();\n"
    "  const pathname = usePathname();\n\n"
    "  const clearError = useCallback(() => {\n"
    "    setState(prev => ({ ...prev, error: null }));\n"
    "  }, []);\n\n"
    "  const refreshSession = useCallback(async () => {\n"
    "    try {\n"
    "      const sessionToken = Cookies.get(SESSION_COOKIE);\n"
    "      if (!sessionToken) {\n"
    "        setState({ user: null, isLoading: false, isAuthenticated: false, error: null });\n"
    "        return;\n"
    "      }\n\n"
    "      const response = await fetch(`${API_BASE}/api/admin/auth/me`, {\n"
    "        headers: {\n"
    "          'Authorization': `Bearer ${sessionToken}`,\n"
    "          'Content-Type': 'application/json',\n"
    "        },\n"
    "        credentials: 'include',\n"
    "      });\n\n"
    "      if (response.ok) {\n"
    "        const data = await response.json();\n"
    "        setState({\n"
    "          user: data.user,\n"
    "          isLoading: false,\n"
    "          isAuthenticated: true,\n"
    "          error: null,\n"
    "        });\n"
    "      } else {\n"
    "        Cookies.remove(SESSION_COOKIE);\n"
    "        setState({ user: null, isLoading: false, isAuthenticated: false, error: null });\n"
    "      }\n"
    "    } catch {\n"
    "      Cookies.remove(SESSION_COOKIE);\n"
    "      setState({ user: null, isLoading: false, isAuthenticated: false, error: null });\n"
    "    }\n"
    "  }, []);\n\n"
    "  useEffect(() => {\n"
    "    refreshSession();\n"
    "  }, [refreshSession]);\n\n"
    "  // Redirect to login if not authenticated and not on login page\n"
    "  useEffect(() => {\n"
    "    if (!state.isLoading && !state.isAuthenticated && pathname !== '/login') {\n"
    "      router.push('/login');\n"
    "    }\n"
    "    if (state.isAuthenticated && pathname === '/login') {\n"
    "      router.push('/overview');\n"
    "    }\n"
    "  }, [state.isLoading, state.isAuthenticated, pathname, router]);\n\n"
    "  const login = async (email: string, password: string) => {\n"
    "    setState(prev => ({ ...prev, isLoading: true, error: null }));\n"
    "    try {\n"
    "      const response = await fetch(`${API_BASE}/api/admin/auth/login`, {\n"
    "        method: 'POST',\n"
    "        headers: { 'Content-Type': 'application/json' },\n"
    "        body: JSON.stringify({ email, password }),\n"
    "        credentials: 'include',\n"
    "      });\n\n"
    "      const data = await response.json();\n\n"
    "      if (!response.ok) {\n"
    "        throw new Error(data.detail || 'Login failed');\n"
    "      }\n\n"
    "      if (data.session_token) {\n"
    "        Cookies.set(SESSION_COOKIE, data.session_token, {\n"
    "          secure: process.env.NODE_ENV === 'production',\n"
    "          sameSite: 'lax',\n"
    "          expires: 7,\n"
    "        });\n"
    "      }\n\n"
    "      setState({\n"
    "        user: data.user,\n"
    "        isLoading: false,\n"
    "        isAuthenticated: true,\n"
    "        error: null,\n"
    "      });\n\n"
    "      router.push('/overview');\n"
    "      router.refresh();\n"
    "    } catch (err) {\n"
    "      const message = err instanceof Error ? err.message : 'Login failed';\n"
    "      setState(prev => ({ ...prev, isLoading: false, error: message }));\n"
    "      throw err;\n"
    "    }\n"
    "  };\n\n"
    "  const logout = async () => {\n"
    "    setState(prev => ({ ...prev, isLoading: true }));\n"
    "    try {\n"
    "      const sessionToken = Cookies.get(SESSION_COOKIE);\n"
    "      if (sessionToken) {\n"
    "        await fetch(`${API_BASE}/api/admin/auth/logout`, {\n"
    "          method: 'POST',\n"
    "          headers: {\n"
    "            'Authorization': `Bearer ${sessionToken}`,\n"
    "            'Content-Type': 'application/json',\n"
    "          },\n"
    "          credentials: 'include',\n"
    "        });\n"
    "      }\n"
    "    } finally {\n"
    "      Cookies.remove(SESSION_COOKIE);\n"
    "      setState({ user: null, isLoading: false, isAuthenticated: false, error: null });\n"
    "      router.push('/login');\n"
    "      router.refresh();\n"
    "    }\n"
    "  };\n\n"
    "  return (\n"
    "    <AuthContext.Provider value={{ ...state, login, logout, refreshSession, clearError }}>\n"
    "      {children}\n"
    "    </AuthContext.Provider>\n"
    "  );\n"
    "}\n"
)

